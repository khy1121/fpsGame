package com.fpsgame.client.ui;

import java.awt.*;
import java.lang.reflect.Method;
import java.util.List;
import java.util.Objects;
import javax.swing.*;

/**
 * LobbyCenterCoordinator (lightweight)
 * ------------------------------------------------------------
 * In CENTER area, switches between "Map Vote" and "Character Select" via CardLayout.
 * Network senders (MapVote/SetSelection) are wired loosely (reflection) to avoid
 * hard coupling to higher layers.
 *
 * Usage:
 *   LobbyCenterCoordinator cc = LobbyCenterCoordinator.install(container, netClient);
 *   cc.updateMaps(List.of("terminal","neonCity"));
 *   cc.updateCharacters(List.of("Sage","Piper", ...));
 *
 * Teardown:
 *   cc.uninstall();  // idempotent
 */
public final class LobbyCenterCoordinator {

    /** ???????????????????????(CardLayout) */
    private final JPanel root = new JPanel(new CardLayout());
    private static final String CARD_VOTE   = "vote";
    private static final String CARD_SELECT = "select";

    /** ???? ??????*/
    private final MapVotePanel mapVotePanel   = new MapVotePanel();
    private final CharacterSelectPanel charPanel = new CharacterSelectPanel();

    /** ???? ????NetClient or ClientController ?? */
    private Object netClient;

    /** ???? ????????????? ???????? */
    private final Container parent;

    /** ???? ??? */
    private boolean installed;

    private LobbyCenterCoordinator(Container parent, Object netClient) {
        this.parent = Objects.requireNonNull(parent, "parent");
        this.netClient = netClient; // null ????
    }

    /** ??????????CENTER?????????????????????????????. (?????????? ?????????? */
    public static LobbyCenterCoordinator install(Container container, Object netClient) {
        return installTo(container, netClient);
    }

    /** ??????????????????????????????????????????. (LobbySandboxFrame ????? */
    public static LobbyCenterCoordinator installTo(Container container, Object netClient) {
        LobbyCenterCoordinator c = new LobbyCenterCoordinator(container, netClient);
        c.doInstall();
        return c;
    }

    // ==================== ??? API(EDT ????) ====================

    /** ?????? ?????null/??????) */
    public void updateMaps(List<String> mapIds) {
        runEdt(() -> mapVotePanel.setMaps(mapIds));
    }

    /** ?????????? ?????null/??????) */
    public void updateCharacters(List<String> ids) {
        runEdt(() -> {
            if (ids == null || ids.isEmpty()) {
                charPanel.withDefaultCharacters();
            } else {
                charPanel.setCharacters(ids);
            }
        });
    }

    /** ?????????? ???? */
    public void showVote() {
        runEdt(() -> {
            CardLayout cl = (CardLayout) root.getLayout();
            cl.show(root, CARD_VOTE);
            root.revalidate();
            root.repaint();
        });
    }

    /** ?????????? ???? ???? */
    public void showSelect() {
        runEdt(() -> {
            CardLayout cl = (CardLayout) root.getLayout();
            cl.show(root, CARD_SELECT);
            root.revalidate();
            root.repaint();
        });
    }

    /** ????????? ???(???? ??????; ?????????? ??????????) */
    public void hideAll() {
        runEdt(() -> {
            // ????????????????? ????????? ??????????????? ???????? ?????????
            root.repaint();
        });
    }

    /** ??????? NetClient ??????????????? */
    public void setNetClient(Object netClient) {
        this.netClient = netClient;
        runEdt(this::wireSenders); // ???? ???? ?????
    }

    /** ????(????????? ????) */
    public void uninstall() {
        if (!installed) return;
        runEdt(() -> {
            try {
                try { parent.remove(root); } catch (Throwable ignore) {}
                parent.revalidate();
                parent.repaint();
            } finally {
                installed = false;
            }
        });
    }

    /** ??????? ???????????????????????????? ????????*/
    public JComponent getComponent() { return root; }

    // ==================== ???? ???? ====================

    private void doInstall() {
        runEdt(() -> {
            ensureBorderLayout(parent);

            // ?????????
            root.setOpaque(false);
            root.add(mapVotePanel, CARD_VOTE);
            root.add(charPanel,   CARD_SELECT);

            // ?????????: ?????????????????VOTE ????
            ((CardLayout) root.getLayout()).show(root, CARD_VOTE);

            // ???? ??????????
            wireSenders();

            // ?????
            parent.add(root, BorderLayout.CENTER);
            parent.revalidate();
            parent.repaint();
            installed = true;
        });
    }

    /** ?????????? ??????netClient/???? ?????????? ????????? ???? */
    private void wireSenders() {
        // MapVote: MapVoteSender.send(Object, String)
        mapVotePanel.onSendVote(mapId -> {
            if (netClient == null) return;
            try {
                // 1) netClient??? ????????? ????????????? ????
                Method m = netClient.getClass().getMethod("sendMapVote", int.class);
                // mapId??? ?????????????? ????????????????????0??????????????? ????)
                int idx = safeIndex(mapId);
                m.invoke(netClient, idx);
                return;
            } catch (Throwable ignore) { /* ???? ????????????*/ }
            try {
                Class<?> cls = Class.forName("com.fpsgame.client.net.MapVoteSender");
                Method m = cls.getMethod("send", Object.class, String.class);
                m.invoke(null, netClient, String.valueOf(mapId));
            } catch (Throwable ignore) {
                // ???? ???? ?????????????? ????: ???????????
            }
        });

        // CharacterSelect: SetSelectionSender.send(Object, String)
        charPanel.onSendSelection(chId -> {
            if (netClient == null) return;
            // 1) ????????? ????? team?? ???, char?????????????????????????
            try {
                Method m = netClient.getClass().getMethod("sendSetSelection", int.class, int.class);
                int team = 0; // ?? ???? UI??? ???????????????0
                int chIdx = safeIndex(chId);
                m.invoke(netClient, team, chIdx);
                return;
            } catch (Throwable ignore) { /* ???? ????????????*/ }
            // 2) ???? ?????
            try {
                Class<?> cls = Class.forName("com.fpsgame.client.net.SetSelectionSender");
                Method m = cls.getMethod("send", Object.class, String.class);
                m.invoke(null, netClient, String.valueOf(chId));
            } catch (Throwable ignore) {
                // ???????????
            }
        });
    }

    private static int safeIndex(String id) {
        if (id == null) return 0;
        try { return Integer.parseInt(id.trim()); }
        catch (Exception ignore) { return 0; }
    }

    private static void ensureBorderLayout(Container c) {
        if (!(c.getLayout() instanceof BorderLayout)) {
            Component[] comps = c.getComponents();
            c.setLayout(new BorderLayout());
            for (Component comp : comps) c.add(comp, BorderLayout.CENTER);
        }
    }

    private static void runEdt(Runnable r) {
        if (SwingUtilities.isEventDispatchThread()) r.run();
        else SwingUtilities.invokeLater(r);
    }
}

